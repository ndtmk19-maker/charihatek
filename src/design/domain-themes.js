/**
 * Returns available theme variants for a given domain
 */
export function getVariantsForDomain(domain) {
  return Object.values(THEME_VARIANTS).filter(theme => theme.domain === domain);
}

/**
 * Returns the default theme variant for a given domain
 */
export function getDefaultVariantForDomain(domain) {
  const map = {
    [DOMAINS.TECHNOLOGY]: 'tech-cyber',
    [DOMAINS.INFORMATION_SYSTEMS]: 'is-enterprise',
    [DOMAINS.ECONOMICS]: 'econ-trend',
    [DOMAINS.MANAGEMENT]: 'mgmt-navy-gold',
    [DOMAINS.MEDICINE]: 'med-clinical',
    [DOMAINS.ACCOUNTING]: 'acc-fiscal'
  };
  const themeId = map[domain] || 'econ-trend';
  return THEME_VARIANTS[themeId] || THEME_VARIANTS['econ-trend'];
}
